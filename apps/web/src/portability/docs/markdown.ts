// Markdown documentation (GitHub-flavoured: tables + a Mermaid diagram).

import {
  aspectTypeDocs,
  assetTypeDocs,
  changelogEntries,
  changelogTable,
  filesTable,
  formatDateTime,
  guardrailDoc,
  hierarchyDoc,
  hierarchyOmissionNote,
  issueTable,
  metadataTable,
  summaryData,
  type DocContext,
  type DocTable,
} from "./content";
import { buildDiagramGraph, renderMermaid } from "./diagram";
import { escapeMarkdown, escapeMarkdownCell } from "./escape";
import { SECTION_ANCHORS, enabledSections, type DocOptions, type DocSectionId } from "./options";

function table(t: DocTable): string {
  if (t.rows.length === 0) return "_None._\n";
  const head = `| ${t.headers.map(escapeMarkdownCell).join(" | ")} |`;
  const sep = `| ${t.headers.map(() => "---").join(" | ")} |`;
  const body = t.rows.map((r) => `| ${r.map((c) => escapeMarkdownCell(c)).join(" | ")} |`);
  return [head, sep, ...body].join("\n") + "\n";
}

const p = (text: string) => `${escapeMarkdown(text)}\n`;

type Renderer = (ctx: DocContext, opts: DocOptions) => string[];

const SECTIONS: Record<DocSectionId, Renderer> = {
  metadata: (ctx) => [table(metadataTable(ctx))],
  summary: (ctx) => {
    const s = summaryData(ctx);
    const out = [
      "### Counts\n",
      table(s.counts),
      "### Estimated asset attributes\n",
      table(s.attributes),
      p(s.estimateNote),
      "#### Per asset type\n",
      table(s.perType),
      "### Validation\n",
      table(s.validation),
    ];
    if (s.issues.length) {
      out.push("#### Errors and warnings\n", table(issueTable(s.issues)));
      if (s.omittedIssues) out.push(p(`${s.omittedIssues} more issues are not listed.`));
    } else out.push(p("No errors or warnings."));
    return out;
  },
  aspectTypes: (ctx) => {
    const docs = aspectTypeDocs(ctx);
    if (!docs.length) return [p("The project has no aspect types.")];
    return docs.flatMap((d) => [
      `### ${escapeMarkdown(d.def.name || d.def.idSuffix)}\n`,
      table(d.properties),
      "#### Variables\n",
      table(d.variables),
    ]);
  },
  assetTypes: (ctx) => {
    const docs = assetTypeDocs(ctx);
    if (!docs.length) return [p("The project has no asset types.")];
    return docs.flatMap((d) => [
      `### ${escapeMarkdown(d.def.name || d.def.idSuffix)}\n`,
      table(d.properties),
      "#### Own variables\n",
      table(d.ownVariables),
      "#### Inherited variables\n",
      table(d.inheritedVariables),
      "#### Aspects\n",
      table(d.aspects),
    ]);
  },
  diagram: (ctx) => {
    const graph = buildDiagramGraph(ctx);
    if (!graph.nodes.length) return [p("There are no types to draw.")];
    return [
      p("Solid arrows: inheritance (parent → child). Dashed arrows: aspect usage, labelled with the aspect name."),
      "```mermaid",
      renderMermaid(graph),
      "```\n",
    ];
  },
  hierarchy: (ctx, opts) => {
    const h = hierarchyDoc(ctx, opts.hierarchyMaxNodes, opts.hierarchyMaxDepth);
    const lines = h.lines.map((l) => {
      const hidden = l.hiddenChildren ? ` (+${l.hiddenChildren} below)` : "";
      return `${"  ".repeat(l.depth)}- **${escapeMarkdown(l.name)}** — ${escapeMarkdown(l.typeName)}${hidden}`;
    });
    const note = hierarchyOmissionNote(h);
    return [lines.join("\n") + "\n", ...(note ? [p(note)] : [])];
  },
  files: (ctx) => (ctx.project.files.length ? [table(filesTable(ctx))] : [p("The project has no files.")]),
  changelog: (ctx) => {
    const { entries, omitted } = changelogEntries(ctx);
    return [table(changelogTable(entries)), ...(omitted ? [p(`${omitted} older entries are not listed.`)] : [])];
  },
  guardrails: (ctx) => {
    const g = guardrailDoc(ctx);
    return [
      p(`Profile: ${g.profile}`),
      table(g.recommended),
      table(g.technical),
      "#### Notes\n",
      g.notes.map((n) => `- ${escapeMarkdown(n)}`).join("\n") + "\n",
    ];
  },
};

export function renderMarkdown(ctx: DocContext, opts: DocOptions): string {
  const sections = enabledSections(opts);
  const out: string[] = [
    `# ${escapeMarkdown(ctx.project.name)} — model documentation\n`,
    p(`Generated by Asset Model Studio on ${formatDateTime(ctx.generatedAt)}.`),
  ];
  if (ctx.project.description) out.push(`> ${escapeMarkdown(ctx.project.description)}\n`);
  if (sections.length > 1) {
    out.push("## Contents\n", sections.map((s, i) => `${i + 1}. [${s.title}](#${SECTION_ANCHORS[s.id]})`).join("\n") + "\n");
  }
  for (const s of sections) {
    out.push(`<a id="${SECTION_ANCHORS[s.id]}"></a>\n`, `## ${s.title}\n`, ...SECTIONS[s.id](ctx, opts));
  }
  return out.join("\n");
}
